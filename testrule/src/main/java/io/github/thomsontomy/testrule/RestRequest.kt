package io.github.thomsontomy.testrule

import kotlin.annotation.AnnotationRetention.RUNTIME
import kotlin.annotation.AnnotationTarget.FUNCTION
import kotlin.jvm.JvmRepeatable

/**
 * Declares the HTTP interaction a test performs.
 *
 * A single test method may declare the annotation more than once. Requests and responses are
 * matched **in declaration order**: the first annotation describes the first request the service
 * makes, the second describes the second request, and so on.
 *
 * ```kotlin
 * @Test
 * @RestRequest(
 *     expect = ExpectRequest(path = "/users/me", method = HttpMethod.GET),
 *     respond = RespondWith(bodyText = """{"id":1}""")
 * )
 * @RestRequest(
 *     expect = ExpectRequest(path = "/users/1/repos", method = HttpMethod.GET),
 *     respond = RespondWith(bodyText = "[]")
 * )
 * fun `loads profile then repositories`() = runTest {
 *     val service = rule.getService()
 *     service.me()
 *     service.repos(1)
 * }
 * ```
 *
 * Every declared request is validated after the test body completes. A test that makes fewer or
 * more calls than it declares fails with a diagnostic instead of silently passing.
 *
 * @property expect expectations applied to the captured request
 * @property respond response the mock server returns for that request
 * @see RetrofitTestRule
 * @see ExpectRequest
 * @see RespondWith
 */
@JvmRepeatable(RestRequests::class)
@Retention(RUNTIME)
@Target(FUNCTION)
annotation class RestRequest(val expect: ExpectRequest = ExpectRequest(), val respond: RespondWith = RespondWith())

/**
 * Container for repeated [RestRequest] annotations.
 *
 * This type is generated by the compiler for Java interoperability; Kotlin users should simply
 * repeat [RestRequest] and never reference this annotation directly.
 */
@Retention(RUNTIME)
@Target(FUNCTION)
annotation class RestRequests(vararg val value: RestRequest)

/**
 * Expectations applied to a captured HTTP request.
 *
 * Every property is optional. An empty [path], an [HttpMethod.ANY] [method] and empty body
 * properties mean "do not validate this aspect". When both [bodyText] and [bodyFile] are set the
 * test fails with an explicit error rather than silently preferring one of them.
 *
 * @property path expected request path, relative to the mock server. A query string may be
 * included for convenience (`/api/test?id=john`); it is validated parameter by parameter and is
 * therefore order independent.
 * @property method expected HTTP method, or [HttpMethod.ANY] to accept any method
 * @property query individual query parameters that must be present
 * @property headers request headers that must be present
 * @property bodyText expected request body as inline text
 * @property bodyFile expected request body loaded from a resource file or file system path
 * @see QueryParam
 * @see HeaderValue
 */
@Retention(RUNTIME)
annotation class ExpectRequest(
    val path: String = "",
    val method: HttpMethod = HttpMethod.ANY,
    val query: Array<QueryParam> = [],
    val headers: Array<HeaderValue> = [],
    val bodyText: String = "",
    val bodyFile: String = "",
)

/**
 * Describes the response the mock server returns.
 *
 * @property code HTTP status code
 * @property bodyText response body as inline text. Defaults to an empty body.
 * @property bodyFile response body loaded from a resource file or file system path
 * @property headers response headers to send
 * @property delayMs delay applied before the response body is written, useful for testing
 * loading states and timeouts. Remember to configure a client timeout shorter than this value.
 * @property socketBehavior low level socket behaviour, useful for simulating network failures
 * @see SocketBehavior
 */
@Retention(RUNTIME)
annotation class RespondWith(
    val code: Int = 200,
    val bodyText: String = "",
    val bodyFile: String = "",
    val headers: Array<HeaderValue> = [],
    val delayMs: Long = 0,
    val socketBehavior: SocketBehavior = SocketBehavior.NORMAL,
)

/**
 * A query parameter that must be present on the captured request.
 *
 * @property name parameter name
 * @property value expected (decoded) parameter value
 */
@Retention(RUNTIME)
annotation class QueryParam(val name: String, val value: String)

/**
 * A header name/value pair used for request expectations and response definitions.
 *
 * @property name header name, matched case insensitively
 * @property value header value
 */
@Retention(RUNTIME)
annotation class HeaderValue(val name: String, val value: String)

/**
 * Supported HTTP methods for [ExpectRequest.method].
 *
 * [ANY] disables method validation.
 */
enum class HttpMethod {
    ANY,
    GET,
    POST,
    PUT,
    PATCH,
    DELETE,
    HEAD,
    OPTIONS,
}

/**
 * Low level socket behaviours used to simulate network failures.
 *
 * Only [NORMAL] produces a regular HTTP response. The remaining values map to OkHttp's
 * `SocketPolicy` and are intended for retry, timeout and resilience tests.
 */
enum class SocketBehavior {
    /** Serve the response normally. */
    NORMAL,

    /** Close the connection before reading the request. */
    DISCONNECT_AT_START,

    /** Read the request, then close the connection without responding. */
    DISCONNECT_AFTER_REQUEST,

    /** Serve the response, then close the connection. */
    DISCONNECT_AT_END,

    /** Never respond, leaving the client waiting until it times out. */
    NO_RESPONSE,

    /** Accept the connection but never read the request. */
    STALL_AT_START,

    /** Do not read the request body. */
    DO_NOT_READ_REQUEST_BODY,
}
